#!/usr/bin/env python3
"""Keep the C++ interface table in step with the Python interface catalog.

The Python catalog (python/example/core/api_catalog.py) lists every MQTT topic with its message
type. The C++ client has the same table in cpp/src/catalog_table.inc. This tool reads the Python
file with the standard library only (no imports of the project, so no paho or protobuf needed).

  catalog_tool.py emit    print the table for catalog_table.inc
  catalog_tool.py check   compare the table in catalog_table.inc with the catalog; exit 1 on a
                          difference (used by the catalog_drift test)

Known difference, kept on purpose: the catalog lists report/device_config, but the device has no
such topic and the public proto defines no DeviceConfigReport message, so the C++ table leaves it
out. See SKIPPED_REPORTS.
"""
import ast
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CATALOG = os.path.normpath(os.path.join(HERE, "..", "..", "python", "example", "core", "api_catalog.py"))
TABLE = os.path.normpath(os.path.join(HERE, "..", "src", "catalog_table.inc"))

# (interface key, direction) pairs that exist in the catalog but not on the device.
SKIPPED_REPORTS = {("device_config", "report")}

HEADER = """// Generated by cpp/tools/catalog_tool.py emit from python/example/core/api_catalog.py.
// Do not edit by hand: the catalog_drift test compares this file with the Python catalog.
//
// LIXEL_API(key, request topic, request message, response topic, response message,
//           report topic, report message)
// nullptr marks an endpoint the interface does not have. An empty message name ("")
// means the payload is JSON text, not protobuf (the heartbeat).
"""


def _endpoint(call):
    """_req("topic", "Message") -> (topic, message)"""
    if not (isinstance(call, ast.Call) and len(call.args) == 2):
        raise ValueError("unexpected endpoint expression")
    topic, msg = (a.value for a in call.args)
    return topic, msg


def read_catalog(path=CATALOG):
    tree = ast.parse(open(path, encoding="utf-8").read())
    rows = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and getattr(node.func, "id", "") == "ApiInterface"):
            continue
        kw = {k.arg: k.value for k in node.keywords}
        key = kw["key"].value
        row = {"key": key, "request": None, "response": None, "report": None}
        for direction in ("request", "response", "report"):
            if direction in kw:
                if (key, direction) in SKIPPED_REPORTS:
                    continue
                row[direction] = _endpoint(kw[direction])
        rows.append(row)
    return rows


def _fmt(ep):
    return "nullptr, nullptr" if ep is None else '"%s", "%s"' % ep


def emit():
    out = [HEADER]
    for r in read_catalog():
        out.append('LIXEL_API("%s", %s, %s, %s)' % (r["key"], _fmt(r["request"]), _fmt(r["response"]), _fmt(r["report"])))
    return "\n".join(out) + "\n"


def read_table(path=TABLE):
    rows = []
    pat = re.compile(r'^LIXEL_API\("([^"]+)",\s*(.+)\)\s*$')
    for line in open(path, encoding="utf-8"):
        m = pat.match(line.strip())
        if not m:
            continue
        parts = re.findall(r'"([^"]*)"|nullptr', m.group(2))
        raw = re.findall(r'("[^"]*"|nullptr)', m.group(2))
        vals = [None if t == "nullptr" else t.strip('"') for t in raw]
        if len(vals) != 6:
            raise ValueError("bad row: " + line)
        pair = lambda a, b: None if a is None else (a, b)  # noqa: E731
        rows.append({"key": m.group(1), "request": pair(vals[0], vals[1]),
                     "response": pair(vals[2], vals[3]), "report": pair(vals[4], vals[5])})
    return rows


def check():
    py = {r["key"]: r for r in read_catalog()}
    cc = {r["key"]: r for r in read_table()}
    problems = []
    for key in sorted(set(py) - set(cc)):
        problems.append("interface in the Python catalog but not in the C++ table: " + key)
    for key in sorted(set(cc) - set(py)):
        problems.append("interface in the C++ table but not in the Python catalog: " + key)
    for key in sorted(set(py) & set(cc)):
        for d in ("request", "response", "report"):
            if py[key][d] != cc[key][d]:
                problems.append("%s.%s differs: python=%r c++=%r" % (key, d, py[key][d], cc[key][d]))
    topics = sum(1 for r in cc.values() for d in ("request", "response", "report") if r[d])
    if problems:
        print("catalog drift:")
        for p in problems:
            print("  " + p)
        return 1
    print("catalog in step: %d interfaces, %d topics" % (len(cc), topics))
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "emit":
        sys.stdout.write(emit())
    elif cmd == "check":
        sys.exit(check())
    else:
        print(__doc__)
        sys.exit(2)
